// MARK: - Shadow

struct SSShadow {
    let color: Color
    let radius: CGFloat
    let x: CGFloat
    let y: CGFloat

    static let soft = SSShadow(color: .black.opacity(0.08), radius: 12, x: 0, y: 4)
    static let elevated = SSShadow(color: .black.opacity(0.14), radius: 22, x: 0, y: 10)
}

extension View {
    func ssShadow(_ shadow: SSShadow = .soft) -> some View {
        self.shadow(color: shadow.color, radius: shadow.radius, x: shadow.x, y: shadow.y)
    }
}

