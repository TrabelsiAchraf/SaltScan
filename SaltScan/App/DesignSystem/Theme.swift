// MARK: - Severity

enum SSSeverity {
    case low, medium, high

    var color: Color {
        switch self {
        case .low: .ssSeverityLow
        case .medium: .ssSeverityMedium
        case .high: .ssSeverityHigh
        }
    }

    var iconName: String {
        switch self {
        case .low: "arrow.down.forward.circle.fill"
        case .medium: "arrow.right.circle.fill"
        case .high: "arrow.up.forward.circle.fill"
        }
    }

    var localizedLabelKey: LocalizedStringKey {
        switch self {
        case .low: "ds.severity.low"
        case .medium: "ds.severity.medium"
        case .high: "ds.severity.high"
        }
    }

    /// Classify from salt (g / 100g), per standard food labelling thresholds.
    static func fromSaltPer100g(_ saltG: Double) -> SSSeverity {
        if saltG > 1.5 { .high }
        else if saltG >= 0.5 { .medium }
        else { .low }
    }

    /// Classify from sodium (g / 100g) by converting to salt (×2.5).
    static func fromSodiumPer100g(_ sodiumG: Double) -> SSSeverity {
        fromSaltPer100g(sodiumG * 2.5)
    }
}
